PIX = {'.': 1, '#': 2, '+': 3}


def stamp(px, col, rows, tile_row=GLYPH_ROW):
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            px[col * 8 + x, tile_row * 8 + y] = PIX[ch]


def main():
    im = Image.open(BMP).copy()        # a mapped BMP is read-only
    assert im.mode == 'P' and im.size == (256, 256), (im.mode, im.size)
    px = im.load()
    glyphs = [DIGITS[i:i + 8] for i in range(0, len(DIGITS), 8)]
    glyphs += [SYMBOLS[i:i + 8] for i in range(0, len(SYMBOLS), 8)]
    glyphs += [ICONS[i:i + 8] for i in range(0, len(ICONS), 8)]
    for col, rows in enumerate(glyphs):
        assert len(rows) == 8 and all(len(r) == 8 for r in rows), col
        stamp(px, col, rows)
    for col, letter in enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
        stamp(px, col, LETTERS[letter], LETTER_ROW)
    for col, rows in enumerate(BOX):
        stamp(px, col, rows, BOX_ROW)
    im.save(BMP)
    print(f"{len(glyphs)} glyphs stamped on tile row {GLYPH_ROW}, "
          f"26 letters on row {LETTER_ROW}, {len(BOX)} box tiles on row {BOX_ROW} of {BMP}")


if __name__ == '__main__':
    main()
